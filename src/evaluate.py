"""Evaluate detectors against the injected synthetic scenarios.

Unit of evaluation: one user-day in the evaluation window.
  positive  = the user-day contains an event labelled `injected_risk`
  negative  = everything else, including `benign_unusual` (approved but unusual work)

Labels are joined here, after detection; the detectors never see them.

Usage:
    python -m src.evaluate                    # evaluate data/synthetic
    python -m src.evaluate --holdout-seed 99  # also regenerate + evaluate an unseen seed
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from src.config import OUTPUT_DIR, ROOT
from src.detector import PipelineResult, run_pipeline
from src.generate_data import generate

METHODS = {
    "rules (score >= 40)": lambda f: f["risk_label"].isin(["medium", "high"]),
    "isolation_forest": lambda f: f["if_outlier"],
    "rules OR isolation_forest": lambda f: f["risk_label"].isin(["medium", "high"]) | f["if_outlier"],
}


def label_user_days(p: PipelineResult) -> pd.DataFrame:
    ev = p.events[p.events["day"].isin(p.findings["day"].unique())]
    g = ev.groupby(["user_id", "day"]).agg(
        injected=("ground_truth", lambda s: (s == "injected_risk").any()),
        benign_unusual=("ground_truth", lambda s: (s == "benign_unusual").any()),
        scenario=("scenario_id", lambda s: ",".join(sorted({x for x in s if x}))),
    )
    return p.findings.merge(g, left_on=["user_id", "day"], right_index=True, how="left")


def metrics(flag: pd.Series, truth: pd.Series) -> dict:
    tp = int((flag & truth).sum())
    fp = int((flag & ~truth).sum())
    fn = int((~flag & truth).sum())
    tn = int((~flag & ~truth).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn,
            "precision": round(precision, 3), "recall": round(recall, 3), "f1": round(f1, 3)}


def evaluate(p: PipelineResult) -> dict:
    m = label_user_days(p)
    truth = m["injected"].astype(bool)
    result = {"user_days": len(m), "positives": int(truth.sum()),
              "benign_unusual_days": int(m["benign_unusual"].sum()),
              "insufficient_baseline_days": int((m["risk_label"] == "insufficient_baseline").sum()),
              "methods": {}, "per_scenario": {}, "false_positives": {}}
    for name, fn in METHODS.items():
        flag = fn(m).astype(bool)
        result["methods"][name] = metrics(flag, truth)
        scn = m[m["scenario"] != ""]
        per = {}
        for s, grp in scn.groupby("scenario"):
            per[s] = f"{int(fn(grp).sum())}/{len(grp)}"
        result["per_scenario"][name] = per
        fps = m[flag & ~truth]
        result["false_positives"][name] = [
            {"user_id": r.user_id, "day": str(r.day), "score": int(r.risk_score), "reasons": r.reasons,
             "benign_unusual": bool(r.benign_unusual)} for r in fps.itertuples()][:25]
    return result


def to_markdown(results: dict[str, dict]) -> str:
    lines = ["# Evaluation results (generated by `python -m src.evaluate`)", "",
             "Synthetic data only. Numbers describe this demo dataset, not real-world performance.", ""]
    for dataset, r in results.items():
        lines += [f"## Dataset: {dataset}", "",
                  f"- Evaluation user-days: {r['user_days']}  |  injected-risk user-days: {r['positives']}  |  "
                  f"benign-unusual user-days: {r['benign_unusual_days']}  |  insufficient-baseline user-days: "
                  f"{r['insufficient_baseline_days']}", "",
                  "| Method | TP | FP | FN | Precision | Recall | F1 |", "|---|---:|---:|---:|---:|---:|---:|"]
        for name, mm in r["methods"].items():
            lines.append(f"| {name} | {mm['tp']} | {mm['fp']} | {mm['fn']} | {mm['precision']:.3f} | "
                         f"{mm['recall']:.3f} | {mm['f1']:.3f} |")
        scns = sorted({s for per in r["per_scenario"].values() for s in per})
        lines += ["", "Per-scenario detections (flagged / injected user-days):", "",
                  "| Scenario | " + " | ".join(r["per_scenario"]) + " |",
                  "|---|" + "---:|" * len(r["per_scenario"])]
        for s in scns:
            lines.append(f"| {s} | " + " | ".join(per.get(s, "-") for per in r["per_scenario"].values()) + " |")
        fps = r["false_positives"]["rules (score >= 40)"]
        lines += ["", f"Rule false positives ({len(fps)} shown):", ""]
        lines += [f"- {f['user_id']} {f['day']} score {f['score']} ({f['reasons']})"
                  + (" — approved change record exists (SCN-06)" if f["benign_unusual"] else "") for f in fps]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--holdout-seed", type=int, default=None)
    args = parser.parse_args()

    results = {"development (seed 8, data/synthetic)": evaluate(run_pipeline())}
    if args.holdout_seed is not None:
        out = OUTPUT_DIR / f"holdout_seed_{args.holdout_seed}"
        out.mkdir(parents=True, exist_ok=True)
        events, _, changes, _ = generate(100, args.holdout_seed)
        events.to_csv(out / "events.csv", index=False)
        changes.to_csv(out / "change_records.csv", index=False)
        results[f"held-out (seed {args.holdout_seed})"] = evaluate(
            run_pipeline(out / "events.csv", out / "change_records.csv"))

    OUTPUT_DIR.mkdir(exist_ok=True)
    (OUTPUT_DIR / "metrics.json").write_text(json.dumps(results, indent=2))
    md = to_markdown(results)
    (ROOT / "docs" / "evaluation_results.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
